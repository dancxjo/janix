//! Framebuffer text console for early boot logging
//!
//! Two modes:
//! - Default: Centered single-line status (progress indicator)
//! - `boot-terminal` feature: Full scrolling terminal console

use crate::framebuffer::Framebuffer;
use spin::Mutex;

/// Global console instance
pub static CONSOLE: Mutex<Option<FbConsole>> = Mutex::new(None);

/// Flag to disable console when compositor takes over
/// Set this via `disable()` when bloom is active
use core::sync::atomic::{AtomicBool, Ordering};
pub static CONSOLE_DISABLED: AtomicBool = AtomicBool::new(false);

// Font metrics
const CHAR_WIDTH: usize = 8;
const CHAR_HEIGHT: usize = 13;

// Colors - Thing-OS blue background for status mode
const FG_COLOR: u32 = 0x00_FF_FF_FF; // White
#[cfg(feature = "boot-terminal")]
const BG_COLOR: u32 = 0x00_1E_1E_1E; // Dark gray for terminal
#[cfg(not(feature = "boot-terminal"))]
const BG_COLOR: u32 = 0x00_00_33_66; // Thing-OS blue for status

/// Console dimensions and state
pub struct FbConsole {
    /// Framebuffer width in pixels
    width: u32,
    /// Framebuffer height in pixels
    height: u32,
    /// Framebuffer pitch (bytes per row)
    pitch: u32,
    /// Raw framebuffer pointer
    fb_ptr: *mut u32,
    #[cfg(feature = "boot-terminal")]
    /// Current cursor column (0-indexed)
    col: usize,
    #[cfg(feature = "boot-terminal")]
    /// Current cursor row (0-indexed)
    row: usize,
    /// Maximum columns
    cols: usize,
    #[cfg(feature = "boot-terminal")]
    /// Maximum rows
    rows: usize,
    #[cfg(feature = "boot-terminal")]
    /// Text buffer for scrolling (rows * cols chars)
    buffer: [[u8; 160]; 60],
    #[cfg(not(feature = "boot-terminal"))]
    /// Current status message (centered)
    status_buf: [u8; 160],
    #[cfg(not(feature = "boot-terminal"))]
    /// Length of current status message
    status_len: usize,
}

unsafe impl Send for FbConsole {}

impl FbConsole {
    /// Create a new console from framebuffer info
    pub fn new(fb: &Framebuffer) -> Self {
        let cols = (fb.width as usize) / CHAR_WIDTH;
        #[cfg(feature = "boot-terminal")]
        let rows = (fb.height as usize) / CHAR_HEIGHT;

        // Clamp to buffer limits
        let cols = cols.min(160);
        #[cfg(feature = "boot-terminal")]
        let rows = rows.min(60);

        Self {
            width: fb.width,
            height: fb.height,
            pitch: fb.pitch,
            fb_ptr: fb.addr,
            #[cfg(feature = "boot-terminal")]
            col: 0,
            #[cfg(feature = "boot-terminal")]
            row: 0,
            cols,
            #[cfg(feature = "boot-terminal")]
            rows,
            #[cfg(feature = "boot-terminal")]
            buffer: [[b' '; 160]; 60],
            #[cfg(not(feature = "boot-terminal"))]
            status_buf: [b' '; 160],
            #[cfg(not(feature = "boot-terminal"))]
            status_len: 0,
        }
    }

    /// Clear the screen with background color
    pub fn clear(&mut self) {
        let buffer = unsafe {
            core::slice::from_raw_parts_mut(
                self.fb_ptr,
                (self.pitch as usize * self.height as usize) / 4,
            )
        };

        for y in 0..self.height as usize {
            let row_start = (y * self.pitch as usize) / 4;
            let row_end = row_start + self.width as usize;
            if row_end <= buffer.len() {
                buffer[row_start..row_end].fill(BG_COLOR);
            }
        }

        #[cfg(feature = "boot-terminal")]
        {
            for row in self.buffer.iter_mut() {
                row.fill(b' ');
            }
            self.col = 0;
            self.row = 0;
        }

        #[cfg(not(feature = "boot-terminal"))]
        {
            self.status_buf.fill(b' ');
            self.status_len = 0;
        }
    }

    /// Write a single character to the console
    #[cfg(feature = "boot-terminal")]
    pub fn put_char(&mut self, c: u8) {
        match c {
            b'\n' => {
                self.col = 0;
                self.row += 1;
                if self.row >= self.rows {
                    self.scroll();
                }
            }
            b'\r' => {
                self.col = 0;
            }
            b'\t' => {
                let next_tab = (self.col + 8) & !7;
                while self.col < next_tab && self.col < self.cols {
                    self.put_visible_char(b' ');
                }
            }
            0x08 => {
                if self.col > 0 {
                    self.col -= 1;
                    self.put_visible_char(b' ');
                    self.col -= 1;
                }
            }
            c if c >= 0x20 && c < 0x7F => {
                self.put_visible_char(c);
            }
            _ => {}
        }
    }

    /// Status mode: just accumulate into status buffer, auto-refresh on newline
    #[cfg(not(feature = "boot-terminal"))]
    pub fn put_char(&mut self, c: u8) {
        match c {
            b'\n' => {
                // Draw current status centered, then reset
                self.draw_centered_status();
                self.status_buf.fill(b' ');
                self.status_len = 0;
            }
            b'\r' => {
                self.status_len = 0;
            }
            c if c >= 0x20 && c < 0x7F => {
                if self.status_len < 160 {
                    self.status_buf[self.status_len] = c;
                    self.status_len += 1;
                }
            }
            _ => {}
        }
    }

    /// Draw the status message centered on screen
    #[cfg(not(feature = "boot-terminal"))]
    fn draw_centered_status(&mut self) {
        // Calculate center row
        let center_row = (self.height as usize / CHAR_HEIGHT) / 2;
        let center_y = center_row * CHAR_HEIGHT;

        // Clear just the center row area
        let buffer = unsafe {
            core::slice::from_raw_parts_mut(
                self.fb_ptr,
                (self.pitch as usize * self.height as usize) / 4,
            )
        };

        for gy in 0..CHAR_HEIGHT {
            let py = center_y + gy;
            if py < self.height as usize {
                let row_start = (py * self.pitch as usize) / 4;
                let row_end = row_start + self.width as usize;
                if row_end <= buffer.len() {
                    buffer[row_start..row_end].fill(BG_COLOR);
                }
            }
        }

        // Calculate horizontal centering
        let text_width = self.status_len * CHAR_WIDTH;
        let start_x = if text_width < self.width as usize {
            (self.width as usize - text_width) / 2
        } else {
            0
        };
        let start_col = start_x / CHAR_WIDTH;

        // Draw each character
        for i in 0..self.status_len {
            let c = self.status_buf[i];
            if c != b' ' {
                self.draw_char_at_pixel(start_x + i * CHAR_WIDTH, center_y, c);
            }
        }
    }

    /// Draw a character at pixel coordinates
    #[cfg(not(feature = "boot-terminal"))]
    fn draw_char_at_pixel(&mut self, x: usize, y: usize, c: u8) {
        let glyph = get_glyph(c);

        let buffer = unsafe {
            core::slice::from_raw_parts_mut(
                self.fb_ptr,
                (self.pitch as usize * self.height as usize) / 4,
            )
        };

        for gy in 0..CHAR_HEIGHT {
            let py = y + gy;
            if py >= self.height as usize {
                break;
            }

            let row_byte = glyph[gy];
            for gx in 0..CHAR_WIDTH {
                let px = x + gx;
                if px >= self.width as usize {
                    break;
                }

                let pixel_on = (row_byte >> (7 - gx)) & 1 != 0;
                if pixel_on {
                    let offset = (py * self.pitch as usize) / 4 + px;
                    if offset < buffer.len() {
                        buffer[offset] = FG_COLOR;
                    }
                }
            }
        }
    }

    #[cfg(feature = "boot-terminal")]
    fn put_visible_char(&mut self, c: u8) {
        if self.row >= self.rows {
            self.scroll();
        }

        if self.col < 160 && self.row < 60 {
            self.buffer[self.row][self.col] = c;
        }

        self.draw_char(self.col, self.row, c);

        self.col += 1;
        if self.col >= self.cols {
            self.col = 0;
            self.row += 1;
            if self.row >= self.rows {
                self.scroll();
            }
        }
    }

    #[cfg(feature = "boot-terminal")]
    fn draw_char(&mut self, col: usize, row: usize, c: u8) {
        let x = col * CHAR_WIDTH;
        let y = row * CHAR_HEIGHT;

        let glyph = get_glyph(c);

        let buffer = unsafe {
            core::slice::from_raw_parts_mut(
                self.fb_ptr,
                (self.pitch as usize * self.height as usize) / 4,
            )
        };

        for gy in 0..CHAR_HEIGHT {
            let py = y + gy;
            if py >= self.height as usize {
                break;
            }

            let row_byte = glyph[gy];
            for gx in 0..CHAR_WIDTH {
                let px = x + gx;
                if px >= self.width as usize {
                    break;
                }

                let pixel_on = (row_byte >> (7 - gx)) & 1 != 0;
                let color = if pixel_on { FG_COLOR } else { BG_COLOR };

                let offset = (py * self.pitch as usize) / 4 + px;
                if offset < buffer.len() {
                    buffer[offset] = color;
                }
            }
        }
    }

    #[cfg(feature = "boot-terminal")]
    fn scroll(&mut self) {
        for i in 1..60 {
            self.buffer[i - 1] = self.buffer[i];
        }
        self.buffer[59].fill(b' ');

        if self.row > 0 {
            self.row -= 1;
        }

        self.redraw();
    }

    #[cfg(feature = "boot-terminal")]
    fn redraw(&mut self) {
        let buffer = unsafe {
            core::slice::from_raw_parts_mut(
                self.fb_ptr,
                (self.pitch as usize * self.height as usize) / 4,
            )
        };

        for y in 0..self.height as usize {
            let row_start = (y * self.pitch as usize) / 4;
            let row_end = row_start + self.width as usize;
            if row_end <= buffer.len() {
                buffer[row_start..row_end].fill(BG_COLOR);
            }
        }

        for row in 0..self.rows.min(60) {
            for col in 0..self.cols.min(160) {
                let c = self.buffer[row][col];
                if c != b' ' {
                    self.draw_char(col, row, c);
                }
            }
        }
    }
}

/// Initialize the global console with framebuffer
pub fn init(fb: &Framebuffer) {
    let mut console = FbConsole::new(fb);
    console.clear();
    *CONSOLE.lock() = Some(console);
}

/// Disable the boot console (call when compositor takes over)
pub fn disable() {
    CONSOLE_DISABLED.store(true, Ordering::Relaxed);
}

/// Check if console is disabled
pub fn is_disabled() -> bool {
    CONSOLE_DISABLED.load(Ordering::Relaxed)
}

/// Write a character to the console (if initialized and not disabled)
pub fn put_char(c: u8) {
    if CONSOLE_DISABLED.load(Ordering::Relaxed) {
        return;
    }
    if let Some(ref mut console) = *CONSOLE.lock() {
        console.put_char(c);
    }
}

